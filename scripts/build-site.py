"""Build the static collection using an explicit list of public source files."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit, unquote
import argparse
import re
import shutil
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'dist'
PUBLIC_ROOT = ['index.html', 'collection.css', 'collection.js', 'material-ui.css',
               'material-ui.js', 'material-docs.css', 'material-docs.js',
               'material-refinement.css', 'material-refinement.js',
               'raster-grid.html', 'README.md', 'docs/motion-foundation.md', 'docs/style-studies.md']


class References(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        for attribute in ('href', 'src'):
            if attrs.get(attribute):
                self.links.append(attrs[attribute])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--no-zip', action='store_true')
    args = parser.parse_args()
    # Never remove a path outside this exact, previously generated output folder.
    if DEST.is_symlink() or DEST.resolve().parent != ROOT or DEST.name != 'dist':
        raise RuntimeError('Unsafe output path')
    marker = DEST / '.ui-collection-build'
    if DEST.exists():
        if not marker.is_file():
            raise RuntimeError('dist exists without the build marker; refusing to overwrite it')
        shutil.rmtree(DEST.resolve())
    DEST.mkdir()
    marker.write_text('Generated by scripts/build-site.py\n', encoding='utf-8')
    sources = [ROOT / name for name in PUBLIC_ROOT]
    for directory in ('raster-ui', 'soft-ui', 'surface-ui', 'minimal-ui', 'expressive-ui',
                      'liquid-ui', 'brutal-ui', 'spatial-ui', 'design-kit'):
        sources += [p for p in (ROOT / directory).rglob('*')
                    if p.is_file() and p.suffix in ('.html', '.css', '.js', '.json', '.md')]
    for source in sources:
        target = DEST / source.relative_to(ROOT)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
    (DEST / '.nojekyll').touch()
    failures = []
    for page in DEST.rglob('*.html'):
        parsed = References()
        parsed.feed(page.read_text(encoding='utf-8'))
        for link in parsed.links:
            url = urlsplit(link)
            if url.scheme or url.netloc or not url.path:
                continue
            if url.path.startswith('/'):
                failures.append(f'{page.relative_to(DEST)}: absolute path {link}')
                continue
            target = (page.parent / unquote(url.path)).resolve()
            if not target.is_relative_to(DEST.resolve()) or not target.exists():
                failures.append(f'{page.relative_to(DEST)}: missing {link}')
    for file in DEST.rglob('*'):
        if file.is_file() and file.suffix in ('.html', '.js', '.css'):
            if re.search(r'https?://(?:localhost|127\.0\.0\.1)', file.read_text(encoding='utf-8')):
                failures.append(f'{file.relative_to(DEST)}: local development address')
    if failures:
        raise RuntimeError('\n'.join(failures))
    count = sum(p.is_file() for p in DEST.rglob('*'))
    print(f'Built {count} static files; all HTML file references resolve under a project subpath.')
    if not args.no_zip:
        archive = ROOT / 'UI-Collection-static.zip'
        with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as bundle:
            for path in sorted(DEST.rglob('*')):
                if path.is_file() and path.name != '.ui-collection-build':
                    bundle.write(path, path.relative_to(DEST))
        print(f'Created {archive.name}')


if __name__ == '__main__':
    main()
